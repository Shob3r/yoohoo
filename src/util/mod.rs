use anyhow::Result;

const ASSETS_BASE: &str = "https://aedes.elysiae.app/";

pub fn normalize_game_name(game_code: &str) -> Result<String> {
    let res = match game_code {
        "\x62\x68\x33" => "\x48\x6f\x6e\x6b\x61\x69\x20\x49\x6d\x70\x61\x63\x74\x20\x33\x72\x64",
        "\x68\x6b\x34\x65" => "\x47\x65\x6e\x73\x68\x69\x6e\x20\x49\x6d\x70\x61\x63\x74",
        "\x68\x6b\x72\x70\x67" => {
            "\x48\x6f\x6e\x6b\x61\x69\x3a\x20\x53\x74\x61\x72\x20\x52\x61\x69\x6c"
        }
        "\x6e\x61\x70" => "\x5a\x65\x6e\x6c\x65\x73\x73\x20\x5a\x6f\x6e\x65\x20\x5a\x65\x72\x6f",
        _ => "",
    };

    Ok(res.into())
}
